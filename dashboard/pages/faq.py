st.markdown("## :primary[:material/help:] FAQ")
st.caption(
    "Как работает матчинг, как читать показатели, "
    "что значат пороги и графики"
)

# ── Группа 1: Как работает матчинг ───────────────────────────────────────────

st.markdown("### :primary[:material/target:] Как работает матчинг")

with st.expander("Что показывает score у совпадения?"):
    st.markdown(
        "Score — это число от 0 до 1, оценка того, насколько товар из "
        "каталога Radal подходит под позицию в тендере. Чем выше score, "
        "тем выше уверенность системы в совпадении.\n\n"
        "**1.0** — идеальное совпадение по всем признакам "
        "(номер детали, производитель, категория, электрические параметры).  \n"
        "**Около 0.95** — совпадает номер детали и производитель, "
        "остальное косвенно.  \n"
        "**Ниже 0.5** — слабое совпадение, скорее всего разные товары."
    )

with st.expander("Что значат пороги 0.75 и 0.92?"):
    st.markdown(
        "Система делит совпадения на три зоны:\n\n"
        "**Автоматическое принятие** (score ≥ 0.92) — система настолько "
        "уверена, что совпадение принимается без участия человека.  \n"
        "**На проверку** (0.75 ≤ score < 0.92) — пограничная зона. "
        "Совпадение похоже на правильное, но недостаточно уверенное. "
        "Эти случаи выводятся в Ленте с пометкой «На проверку».  \n"
        "**Отклонение** (score < 0.75) — совпадение отбрасывается как ненадёжное.\n\n"
        "Пороги пока зафиксированы. После сбора реальной статистики работы "
        "они будут перенастроены под фактическое поведение."
    )

with st.expander("Откуда берётся итоговый score?"):
    st.markdown(
        "Система сравнивает товар из каталога Radal с позицией в тендере "
        "по нескольким признакам, и каждый признак вносит свой вклад "
        "в итоговое число. Самые важные:\n\n"
        "**Номер детали (PN)** — главный признак, до 60% от итогового score  \n"
        "**Производитель** — до 20%  \n"
        "**Категория товара** — до 8%  \n"
        "**Электрические параметры** (напряжение, ток) — до 4% каждый  \n"
        "**Совпадение слов в описании** — до 4%\n\n"
        "Если совпали и номер детали, и производитель — добавляется "
        "бонус 5% за полное совпадение."
    )
    st.caption(
        ":material/arrow_forward: Полный список с визуализацией — "
        "на странице **Настройки — Веса факторов в score**"
    )

# ── Группа 2: Как читать графики на странице Матчинг ─────────────────────────

st.markdown("### :primary[:material/radar:] Как читать графики на странице Матчинг")

with st.expander("Что показывает радар на пяти осях?"):
    st.markdown(
        "Радар показывает геометрический ответ на вопрос «по каким "
        "именно признакам этот товар совпал с тендером». Пять осей — "
        "номер детали (PN), производитель (MFR), категория, "
        "напряжение (V), ток (A). Если ось закрашена до края — "
        "признак совпал, если короткая — нет.\n\n"
        "Радар не показывает итоговый score. Он показывает, **где именно** "
        "совпало, а не насколько в сумме."
    )

with st.expander("Что показывает кольцо (donut)?"):
    st.markdown(
        "Кольцо — это числовой ответ на тот же вопрос: из каких именно "
        "вкладов сложился итоговый score. Каждый сегмент — один из факторов "
        "из формулы (см. Настройки — Веса факторов). Сегмент «до 1.0» — "
        "это сколько баллов система **не добрала** до идеального матча.\n\n"
        "Радар и кольцо дополняют друг друга: радар отвечает «по каким "
        "признакам совпало», кольцо — «насколько каждый признак повлиял "
        "на число»."
    )

with st.expander("Что значит «На проверку» в Ленте?"):
    st.markdown(
        "Это пограничный случай — score попал в зону 0.75–0.92. Система "
        "не уверена, что это точный матч, и просит человека посмотреть. "
        "Откройте такое совпадение на странице **Матчинг** и решите "
        "вручную: принять или отклонить."
    )

# ── Группа 3: Как тендеры сортируются в Ленте ────────────────────────────────

st.markdown("### :primary[:material/format_list_numbered:] Как тендеры сортируются в Ленте")

with st.expander("Почему один тендер выше другого в Ленте?"):
    st.markdown(
        "В Ленте тендеры сортируются по показателю **Relevance** — это "
        "число, которое объединяет четыре фактора:\n\n"
        "**Качество матча** (40%) — насколько уверенно товар совпадает "
        "с позицией тендера  \n"
        "**Наличие на складе** (25%) — есть ли товар сейчас в наличии  \n"
        "**Маржа** (20%) — насколько выгодная сделка по НМЦ  \n"
        "**Срок** (15%) — насколько близко к дедлайну тендера "
        "(срочные выше)\n\n"
        "То есть один тендер может быть выше другого, даже если у него "
        "score меньше — потому что у него лучше маржа, больше товара "
        "на складе или ближе дедлайн."
    )

with st.expander("Зачем нужны и Score, и Relevance?"):
    st.markdown(
        "Это два разных показателя для двух разных решений:\n\n"
        "**Score** отвечает на вопрос «это правильный товар?» — "
        "он определяет, попадёт ли совпадение в категорию «Авто», "
        "«На проверку» или «Отклонить».  \n"
        "**Relevance** отвечает на вопрос «стоит ли заниматься этим "
        "тендером сейчас?» — он определяет, насколько высоко тендер "
        "окажется в Ленте.\n\n"
        "На совпадение со score 0.98 можно потратить минимум усилий "
        "(точный матч), но если у тендера маленькая маржа, дальний "
        "дедлайн и товара мало на складе — он окажется ниже в Ленте, "
        "чем тендер со score 0.85 и хорошей маржой."
    )

# ── Группа 4: Подключения и развитие системы ─────────────────────────────────

st.markdown("### :primary[:material/cable:] Подключения и развитие системы")

with st.expander("Почему TenderGuru показан как «Отключено»?"):
    st.markdown(
        "Сейчас система работает в режиме демонстрации: тендеры "
        "берутся не из реального источника, а из тестового набора. "
        "Подключение к TenderGuru — следующий шаг разработки. "
        "Это **не сбой**, а текущее состояние системы."
    )

with st.expander("Что такое Splink и почему он «Не активен»?"):
    st.markdown(
        "Splink — это библиотека для умного сопоставления записей. "
        "Сейчас её можно подключить, но матчинг работает на собственном "
        "встроенном алгоритме (он на странице Подключения называется "
        "«Rule-based fallback»). Это сделано намеренно: сначала "
        "проверим, что система в целом работает на простом алгоритме, "
        "потом переключаемся на Splink и сравниваем результат.\n\n"
        "Переключение запланировано после того, как накопится достаточно "
        "данных для калибровки."
    )

with st.expander("Каталог Radal — что в нём сейчас?"):
    st.markdown(
        "Сейчас в каталоге 15 тестовых позиций — этого достаточно, "
        "чтобы показать как работает матчинг. Подключение к реальному "
        "каталогу Radal — отдельный шаг, его параметры будут согласованы "
        "с вами на этапе развёртывания (формат экспорта, расписание "
        "обновления, и т.д.)."
    )

with st.expander("Что появится в ближайших обновлениях?"):
    st.markdown(
        "Ближайшие планируемые улучшения:\n\n"
        "**Получение тендеров из TenderGuru** — реальные тендеры по "
        "подпискам ОКПД2, а не тестовая выборка  \n"
        "**LLM-судья для пограничных случаев** — нейросеть, которая "
        "помогает разобрать случаи из зоны «На проверку»  \n"
        "**Автоматическая рассылка совпадений в Telegram и email** — "
        "без необходимости заходить в дашборд  \n"
        "**Регулярный автоматический запуск матчинга** — например, "
        "раз в сутки в 9:00  \n"
        "**Переход на Splink** — более точный алгоритм матчинга после "
        "набора данных для калибровки\n\n"
        "Конкретные сроки уточнятся по ходу разработки."
    )
